def num(a, k, d=0.0):
    m = re.search(r'\b%s="([^"]*)"' % k, a)
    return float(m.group(1)) if m else d

def element(tag, a, draw):
    if tag == 'line':
        tag, a = 'path', 'd="M%g %gL%g %g"' % (num(a, 'x1'), num(a, 'y1'), num(a, 'x2'), num(a, 'y2'))
    if tag == 'path':
        d = re.search(r'\bd="([^"]*)"', a).group(1)
        return ['p', d, round(parse_path(d).length(), 2)] if draw else ['p', d]
    if tag == 'circle':
        return ['c', num(a, 'cx'), num(a, 'cy'), num(a, 'r'), 1 if 'fill="currentColor"' in a else 0]
    if tag == 'rect':
        return ['r', num(a, 'x'), num(a, 'y'), num(a, 'width'), num(a, 'height'), num(a, 'rx')]
    raise SystemExit('unsupported <%s>' % tag)

out = {}
for sf, (name, moving, motion) in ICONS.items():
    svg = open('%s/%s.svg' % (SRC, name)).read()
    els = re.findall(r'<(path|circle|rect|line)\b([^>]*)/>', svg)
    idx = range(len(els)) if moving is None else moving
    draw = motion[0] == 'draw'
    out[sf] = {
        's': [element(t, a, False) for i, (t, a) in enumerate(els) if i not in idx],
        'm': [element(t, a, draw) for i, (t, a) in enumerate(els) if i in idx],
        'a': motion,
    }

open('lib/drawn-data.ts', 'w').write(
    '// Generated by scripts/gen-icons.py. Shapes: Lucide (ISC). Motions: lucide-animated (MIT).\n'
    'export type Shape = [\'p\', string, number?] | [\'c\', number, number, number, number] | [\'r\', number, number, number, number, number];\n'
    'export type Motion = [\'spin\', number] | [\'ring\', number] | [\'shift\', number, number] | [\'draw\'];\n'
    'export const DRAWN: Record<string, { s: Shape[]; m: Shape[]; a: Motion }> = %s;\n' % json.dumps(out, separators=(',', ':')))
print(len(out), 'icons')
